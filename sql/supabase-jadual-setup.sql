-- ---------------------------------------------------------------------------
-- 1. The schedule
--    One row = one planned visit: a date, the team going, and where.
--    Lokasi is deliberately free text, not a link to one hydrant — a planned
--    visit covers a place ("Hospital Kunak"), which may hold several pili.
--    Tapping it in the app searches the map for that place.
-- ---------------------------------------------------------------------------
create table if not exists public.jadual_pemeriksaan (
  id         bigint generated by default as identity primary key,
  tarikh     date not null,                -- when the visit is planned
  pasukan    text not null,                -- which team, e.g. 'Pasukan A'
  lokasi     text not null,                -- where, e.g. 'Hospital Kunak'
  created_by text,                         -- email of the admin who added it
  district   text not null default 'KUNAK',  -- multi-district foundation (§7.3)
  created_at timestamptz default now()
);

-- If the table already existed, top it up.
alter table public.jadual_pemeriksaan add column if not exists district text not null default 'KUNAK';

-- Sorting is always by date, so give the database an index for it.
create index if not exists jadual_tarikh_idx on public.jadual_pemeriksaan (tarikh);

alter table public.jadual_pemeriksaan enable row level security;


-- ---------------------------------------------------------------------------
-- 2. Who may do what
--    Read: any signed-in user — everyone needs to see the plan.
--    Write: admins only, exactly like hydrants and record cards.
-- ---------------------------------------------------------------------------
drop policy if exists "auth read jadual"    on public.jadual_pemeriksaan;
drop policy if exists "admin insert jadual" on public.jadual_pemeriksaan;
drop policy if exists "admin update jadual" on public.jadual_pemeriksaan;
drop policy if exists "admin delete jadual" on public.jadual_pemeriksaan;

create policy "auth read jadual" on public.jadual_pemeriksaan
  for select to authenticated using (true);

create policy "admin insert jadual" on public.jadual_pemeriksaan
  for insert to authenticated with check (public.can_write(district));

create policy "admin update jadual" on public.jadual_pemeriksaan
  for update to authenticated
  using (public.can_write(district)) with check (public.can_write(district));

create policy "admin delete jadual" on public.jadual_pemeriksaan
  for delete to authenticated using (public.can_write(district));


-- ---------------------------------------------------------------------------
-- 3. Check it worked
--    Expect: jadual_table 1, policies 4, index 1
-- ---------------------------------------------------------------------------
select
  (select count(*) from information_schema.tables
     where table_schema='public' and table_name='jadual_pemeriksaan')     as jadual_table,
  (select count(*) from pg_policies
     where schemaname='public' and tablename='jadual_pemeriksaan')        as policies,
  (select count(*) from pg_indexes
     where schemaname='public' and indexname='jadual_tarikh_idx')         as idx,
  (select count(*) from public.jadual_pemeriksaan)                        as rows_so_far;


-- ============================================================================
--  GOOD TO KNOW
--
--  * Rows are never deleted automatically. A visit whose date has passed
--    stays in the table; the app simply lists upcoming visits first and shows
--    past ones below, greyed out. Delete a row only when it was entered by
--    mistake.
--
--  * There is deliberately no "done" tick. Whether an inspection actually
--    happened is already recorded in hydrant_records (the Pengujian rows the
--    record card writes). Keeping a second flag here would let the two drift
--    apart, and the record card is the one that carries the signature.
--
--  * Until this file is run, the app falls back to storing the schedule in
--    each device's own browser storage and says so on screen. Nothing breaks;
--    the list just is not shared yet.
